export function slugify(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

export const CITIES: readonly City[] = ROWS.map(([name, cc, timeZone, lat, lon, priority, s]) => {
  const slug = s ?? slugify(name);
  return {
    id: slug,
    slug,
    name,
    country: COUNTRY[cc] ?? cc,
    countryCode: cc,
    timeZone,
    lat,
    lon,
    priority,
  };
});

export const CITY_BY_ID: ReadonlyMap<string, City> = new Map(CITIES.map((c) => [c.id, c]));

export function getCity(id: string): City | undefined {
  return CITY_BY_ID.get(id);
}

/** Regional-indicator flag emoji from an ISO alpha-2 code. No image requests. */
export function flagEmoji(countryCode: string): string {
  const cc = countryCode.toUpperCase();
  if (!/^[A-Z]{2}$/.test(cc)) return "";
  return String.fromCodePoint(...[...cc].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}
